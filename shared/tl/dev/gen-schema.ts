// Writes shared/tl/schema.ts: the serialized schema that converted snapshots carry.
//   tldraw/node_modules/.bin/tsx --tsconfig shared/tl/dev/tsconfig.json shared/tl/dev/gen-schema.ts
import { writeFileSync } from 'node:fs'
import { fileURLToPath } from 'node:url'
import { schema } from './schema.ts'

const out = fileURLToPath(new URL('../schema.ts', import.meta.url))
writeFileSync(out, `// Generated by shared/tl/dev/gen-schema.ts from the tldraw fork + razzle-path. Do not edit.
import type { SerializedSchema } from './records.ts'

export const TL_SCHEMA: SerializedSchema = ${JSON.stringify(schema.serialize(), null, '\t')}
`)
console.log('wrote', out)
